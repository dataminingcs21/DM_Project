"""Step 2: exploratory data analysis on the full raw dataset.

Usage (from the project root, with the virtual environment active):

    python scripts/02_run_eda.py
    python scripts/02_run_eda.py --nrows 5000          # quick test on a slice

Outputs:
    reports/eda/tables/   CSV tables (statistics, correlations, class comparison, ...)
    reports/eda/figures/  PNG figures
    reports/eda/eda_report.md   a readable summary pointing to both

The data is read but never changed.  The EDA runs on the uncleaned data: the
cleaning rules are decided after it (Checkpoint 2).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from config import settings
from nids.data import schema
from nids.data.inspector import column_profile, label_by_file, label_distribution
from nids.data.loader import load_raw_data
from nids.eda import eda_plots, eda_stats
from nids.utils.logger import get_logger

logger = get_logger("scripts.run_eda")

SENSITIVITY_THRESHOLDS = (0.90, 0.95, 0.98, 0.99)
TOP_FEATURES = 12


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _markdown_table(df: pd.DataFrame, max_rows: int = 30) -> str:
    """Small Markdown table renderer (no extra dependency)."""
    if df.empty:
        return "_(none)_"
    shown = df.head(max_rows)
    lines = [
        "| " + " | ".join(str(c) for c in shown.columns) + " |",
        "|" + "|".join("---" for _ in shown.columns) + "|",
    ]
    for row in shown.itertuples(index=False):
        cells = [f"{v:.4g}" if isinstance(v, (float, np.floating)) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    if len(df) > max_rows:
        lines.append(f"\n_{len(df) - max_rows} more rows in the CSV file._")
    return "\n".join(lines)


def features_dropped_by_threshold(corr: pd.DataFrame, threshold: float) -> int:
    """Estimate how many features a simple correlation filter would drop at ``threshold``.

    Rule: go through the columns in order and drop a column when it correlates
    (absolute value at or above ``threshold``) with a column that is kept.
    This is an estimate for choosing the threshold; the real filter (File 22)
    is fitted on the training data only.
    """
    names = list(corr.columns)
    values = np.nan_to_num(corr.to_numpy(), nan=0.0)
    kept: list[int] = []
    dropped = 0
    for j in range(len(names)):
        if any(abs(values[i, j]) >= threshold for i in kept):
            dropped += 1
        else:
            kept.append(j)
    return dropped


def _save_table(table: pd.DataFrame, name: str, index: bool = False) -> None:
    table.to_csv(settings.EDA_TABLES_DIR / f"{name}.csv", index=index, encoding="utf-8")


def _top(table: pd.DataFrame, column: str, n: int, by_abs: bool = False) -> list[str]:
    valid = table.dropna(subset=[column])
    order = valid[column].abs().sort_values(ascending=False).index if by_abs else valid[column].sort_values(ascending=False).index
    return valid.loc[order, "column"].head(n).tolist()


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------
def build_report(
    n_rows: int,
    n_features: int,
    distribution: pd.DataFrame,
    pairs: pd.DataFrame,
    sensitivity: pd.DataFrame,
    separation: pd.DataFrame,
    descriptive: pd.DataFrame,
    outliers: pd.DataFrame,
    profile: pd.DataFrame,
    figures: list[Path],
    corr_rows: int,
    cap_per_class: int,
) -> str:
    constants = profile.loc[profile["is_constant"], "column"].tolist()
    skewed = descriptive.dropna(subset=["skewness"])
    skewed = skewed.reindex(skewed["skewness"].abs().sort_values(ascending=False).index)[["column", "skewness", "min", "median", "max"]]
    out_top = outliers.dropna(subset=["outlier_percent"]).nlargest(10, "outlier_percent")
    f_top = separation.dropna(subset=["f_statistic"]).head(15)
    threshold = settings.CORRELATION_THRESHOLD

    lines = [
        "# EDA report",
        "",
        "Generated by `scripts/02_run_eda.py` on the **uncleaned** data. Nothing was changed.",
        "",
        "## Overview",
        f"- Rows: **{n_rows:,}**; feature columns: **{n_features}**; classes: **{len(distribution)}**",
        f"- Correlation was computed on a random sample of up to {corr_rows:,} rows; class comparisons use at most {cap_per_class:,} rows per class.",
        f"- Constant columns ({len(constants)}): {', '.join(f'`{c}`' for c in constants) or 'none'}",
        "",
        "## Class distribution",
        _markdown_table(distribution[["label", "count", "percent"]], 40),
        "",
        f"## Highly correlated pairs (|r| >= {threshold})",
        f"- Pairs found: **{len(pairs)}** (strongest first; all in `tables/high_correlation_pairs.csv`)",
        "",
        _markdown_table(pairs, 30),
        "",
        "### Features a simple correlation filter would drop, by threshold (estimate)",
        _markdown_table(sensitivity),
        "",
        "## Features whose class means differ most (ANOVA F, exploration only)",
        _markdown_table(f_top),
        "",
        "## Most skewed features (finite values)",
        _markdown_table(skewed, 10),
        "",
        "## Largest share of values outside the 1.5 x IQR fences",
        _markdown_table(out_top, 10),
        "",
        "## Figures (`figures/`)",
        *[f"- `{p.name}`" for p in figures],
        "",
        "## What this EDA informs (nothing is decided here)",
        f"1. `SCALER_TYPE` (now `{settings.SCALER_TYPE}`): compare with the skewness and outlier tables and the histograms.",
        f"2. `CORRELATION_THRESHOLD` (now {threshold}): compare with the sensitivity table.",
        "3. Whether any feature looks uninformative or suspicious (class profile and box plots).",
        "4. Cleaning rules (Checkpoint 2), together with the inspection report.",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the exploratory data analysis.")
    parser.add_argument("--raw-dir", type=Path, default=None, help="folder with the CSV files (default: data/raw)")
    parser.add_argument("--nrows", type=int, default=None, help="read only the first N rows of each file (quick test)")
    parser.add_argument("--corr-rows", type=int, default=eda_stats.DEFAULT_CORRELATION_ROWS, help="rows used for the correlation matrix")
    parser.add_argument("--cap-per-class", type=int, default=eda_stats.DEFAULT_CAP_PER_CLASS, help="max rows per class for class comparisons")
    args = parser.parse_args(argv)

    try:
        settings.ensure_directories()
        df, _ = load_raw_data(args.raw_dir, nrows=args.nrows)
        features = schema.get_feature_columns(df.columns)
        tables_dir, figures_dir = settings.EDA_TABLES_DIR, settings.EDA_FIGURES_DIR

        logger.info("Computing statistics")
        profile = column_profile(df, features)
        distribution = label_distribution(df)
        crosstab = label_by_file(df)
        descriptive = eda_stats.descriptive_statistics(df, features)
        outliers = eda_stats.outlier_summary(df, features)
        corr = eda_stats.correlation_matrix(df, features, max_rows=args.corr_rows)
        pairs = eda_stats.high_correlation_pairs(corr)
        medians = eda_stats.class_medians(df, features, cap_per_class=args.cap_per_class)
        separation = eda_stats.feature_class_separation(df, features, cap_per_class=args.cap_per_class)
        sensitivity = pd.DataFrame(
            {"threshold": SENSITIVITY_THRESHOLDS, "features_dropped": [features_dropped_by_threshold(corr, t) for t in SENSITIVITY_THRESHOLDS]}
        )
    except (FileNotFoundError, ValueError) as error:
        logger.error("%s", error)
        return 1

    for name, table in {
        "column_profile": profile, "label_distribution": distribution, "descriptive_statistics": descriptive,
        "outlier_summary": outliers, "high_correlation_pairs": pairs, "feature_class_separation": separation,
        "correlation_threshold_sensitivity": sensitivity,
    }.items():
        _save_table(table, name)
    _save_table(crosstab, "label_by_file", index=True)
    _save_table(corr, "correlation_matrix", index=True)
    _save_table(medians, "class_medians", index=True)

    logger.info("Drawing figures")
    top_f = _top(separation, "f_statistic", TOP_FEATURES)
    most_skewed = _top(descriptive, "skewness", TOP_FEATURES, by_abs=True)
    n_box = min(4, len(top_f))
    figures = [
        eda_plots.plot_class_distribution(distribution, figures_dir / "class_distribution.png"),
        eda_plots.plot_label_by_file(crosstab, figures_dir / "label_by_file.png"),
        eda_plots.plot_missing_and_infinite(profile, figures_dir / "missing_and_infinite.png"),
        eda_plots.plot_outlier_percent(outliers, figures_dir / "outlier_percent.png"),
        eda_plots.plot_skewness(descriptive, figures_dir / "skewness.png"),
        eda_plots.plot_correlation_heatmap(corr, figures_dir / "correlation_heatmap.png"),
        eda_plots.plot_top_f_statistics(separation, figures_dir / "top_f_statistics.png"),
        eda_plots.plot_class_profile(medians, _top(separation, "f_statistic", 20), figures_dir / "class_profile.png"),
        eda_plots.plot_feature_histograms(df, top_f, figures_dir / "histograms_top_f.png"),
        eda_plots.plot_feature_histograms(df, most_skewed, figures_dir / "histograms_most_skewed.png"),
        eda_plots.plot_feature_by_class(df, top_f[:n_box], figures_dir / "boxplots_top_f.png"),
    ]

    report = build_report(
        len(df), len(features), distribution, pairs, sensitivity, separation, descriptive,
        outliers, profile, figures, min(args.corr_rows, len(df)), args.cap_per_class,
    )
    report_path = settings.EDA_TABLES_DIR.parent / "eda_report.md"
    report_path.write_text(report, encoding="utf-8")

    logger.info("EDA finished: %d tables, %d figures", len(list(tables_dir.glob("*.csv"))), len(figures))
    logger.info("Report: %s", report_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())