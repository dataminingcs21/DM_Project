"""Step 1: load the raw CSV files and write an inspection report (Checkpoint 1).

Usage (from the project root, with the virtual environment active):

    python scripts/01_inspect_dataset.py
    python scripts/01_inspect_dataset.py --nrows 2000        # quick test on a slice
    python scripts/01_inspect_dataset.py --raw-dir path\\to\\csv_folder

Outputs in ``reports/inspection/``:
    inspection_summary.json, inspection_report.md,
    column_profile.csv, label_distribution.csv, label_by_file.csv

Nothing is cleaned or changed; the report is what Checkpoint 1 decisions are based on.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

from config import settings
from nids.data.inspector import inspect_dataset
from nids.data.loader import load_raw_data
from nids.utils.io_utils import write_json
from nids.utils.logger import get_logger

logger = get_logger("scripts.inspect_dataset")

# Name-based hint only: columns that look like identifiers or time stamps.
IDENTIFIER_PATTERN = re.compile(r"\b(port|ip|id|timestamp|time)\b", re.IGNORECASE)


def _markdown_table(df: pd.DataFrame, max_rows: int = 40) -> str:
    """Render a small DataFrame as a Markdown table (no extra dependency)."""
    if df.empty:
        return "_(empty)_"
    shown = df.head(max_rows).reset_index(drop=isinstance(df.index, pd.RangeIndex))
    header = "| " + " | ".join(str(c) for c in shown.columns) + " |"
    rule = "|" + "|".join("---" for _ in shown.columns) + "|"
    lines = [header, rule]
    for _, row in shown.iterrows():
        lines.append("| " + " | ".join(str(v) for v in row.tolist()) + " |")
    if len(df) > max_rows:
        lines.append(f"\n_{len(df) - max_rows} more rows in the CSV file._")
    return "\n".join(lines)


def _identifier_candidates(columns: list[str]) -> list[str]:
    return [c for c in columns if IDENTIFIER_PATTERN.search(c)]


def build_markdown_report(summary: dict, tables: dict[str, pd.DataFrame]) -> str:
    labels, values, dups = summary["labels"], summary["values"], summary["duplicates"]
    profile = tables["column_profile"]
    candidates = _identifier_candidates(profile["column"].tolist())

    def lst(items: list) -> str:
        return ", ".join(f"`{i}`" for i in items) if items else "none"

    lines = [
        "# Dataset inspection report",
        "",
        "Generated by `scripts/01_inspect_dataset.py`. Nothing was cleaned or changed.",
        "",
        "## Overview",
        f"- Rows: **{summary['n_rows']:,}**; feature columns: **{summary['n_feature_columns']}**; "
        f"source files: **{summary['n_source_files']}**; memory: {summary['memory_mb']} MB",
        f"- Classes: **{labels['n_classes']}** (missing labels: {labels['n_missing_labels']})",
        "",
        "## Label distribution",
        _markdown_table(tables["label_distribution"]),
        "",
        f"- Classes below the technical minimum of {labels['min_class_samples_rule']} rows: {lst(labels['classes_below_min_samples'])}",
        f"- Classes found in a single source file: {lst(labels['classes_in_a_single_file'])}",
        f"- Labels with odd characters: {lst(labels['labels_with_odd_characters'])}",
        "",
        "## Label by source file",
        _markdown_table(tables["label_by_file"]),
        "",
        "## Values",
        f"- Missing values: {values['n_missing']:,}; infinite values: {values['n_infinite']:,}; "
        f"rows with a missing or infinite value: {values['rows_with_missing_or_infinite']:,}",
        f"- Columns with missing values: {lst(values['columns_with_missing'])}",
        f"- Columns with infinite values: {lst(values['columns_with_infinite'])}",
        f"- Columns with negative values: {lst(values['columns_with_negative'])}",
        f"- Constant columns: {lst(values['constant_columns'])}",
        "",
        "## Duplicates",
        f"- Duplicated rows (features + label): {dups['n_duplicate_rows']:,}",
        f"- Feature vectors with more than one label: {dups['n_conflicting_feature_vectors']:,} "
        f"({dups['n_rows_in_conflicting_vectors']:,} rows)",
        "",
        "## Candidates for `EXCLUDED_FEATURES` (name-based hint only)",
        f"- Columns whose name looks like an identifier or time stamp: {lst(candidates)}",
        "- This is a suggestion from the column names, not a decision. Any exclusion needs a written reason.",
    ]
    if "load" in summary:
        load = summary["load"]
        lines += [
            "",
            "## Loading",
            f"- Encodings used: {load['encodings']}",
            f"- Non-numeric values converted to missing, per file: {load['non_numeric_values_coerced'] or 'none'}",
        ]
    lines += [
        "",
        "## Checkpoint 1 decisions",
        "1. `RARE_CLASS_POLICY`: keep or merge the rare classes listed above.",
        "2. `EXCLUDED_FEATURES`: which columns (if any) to exclude, each with a reason.",
        "3. How to treat labels with odd characters.",
        "4. How to treat duplicated rows and feature vectors with conflicting labels (cleaning step).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Inspect the raw CIC-IDS2017 CSV files.")
    parser.add_argument("--raw-dir", type=Path, default=None, help="folder with the CSV files (default: data/raw)")
    parser.add_argument("--nrows", type=int, default=None, help="read only the first N rows of each file (quick test)")
    args = parser.parse_args(argv)

    try:
        settings.ensure_directories()
        df, load_report = load_raw_data(args.raw_dir, nrows=args.nrows)
        summary, tables = inspect_dataset(df, load_report)
    except (FileNotFoundError, ValueError) as error:
        logger.error("%s", error)
        return 1

    out = settings.INSPECTION_REPORT_DIR
    write_json(summary, out / "inspection_summary.json")
    for name, table in tables.items():
        table.to_csv(out / f"{name}.csv", index=name == "label_by_file", encoding="utf-8")
    (out / "inspection_report.md").write_text(build_markdown_report(summary, tables), encoding="utf-8")

    logger.info("Report written to %s", out)
    logger.info("Rows: %d | features: %d | classes: %d", summary["n_rows"], summary["n_feature_columns"], summary["labels"]["n_classes"])
    return 0


if __name__ == "__main__":
    sys.exit(main())